/** Applique la traduction anglaise aux catégories françaises. */
export function localizeCategories(categories) {
  return categories.map((category) => ({
    ...category,
    ...CATEGORIES_EN[category.id],
    services: category.services.map((service) => {
      const en = SERVICES_EN[service.id];
      if (!en) return service;
      return {
        ...service,
        ...en,
        benefits: service.benefits.map((b, i) => ({ ...b, text: en.benefits[i] ?? b.text })),
      };
    }),
  }));
}
